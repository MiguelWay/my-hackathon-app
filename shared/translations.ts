// The app's translation catalog: every static piece of copy, its screen, its role and both languages.
//
// This file is the seed for the `translations` table and the app's fallback copy while that table is
// being fetched. Once seeded, the table is the editable source of truth: the Translations screen can
// change either language without a deploy. Keys are stable; the English side is the original.

export type Language = "en" | "es";
export type TranslationRole = "all" | "administrator" | "operator";

export interface TranslationEntry {
  key: string;
  screen: string;
  role: TranslationRole;
  context: string;
  english: string;
  spanish: string;
}

export interface TranslationRow extends TranslationEntry {
  id: number;
  sort_order: number;
  updated_at: string;
}

